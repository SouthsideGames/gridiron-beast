// Ability balance pass (polish 2.0, GDD §23.15). For every signature ability, and one species per shared
// trait, play the same 2,000 snaps twice: once with the monster's ability, once with the same monster and
// no ability. Same seeds, same plays, same ratings, so the difference is the ability. Play-to-play memory is
// carried like a real game (a drive every 6 snaps, halves of 30, quarters of 15), so once-per-drive, half
// and game abilities are measured at their real rate. Writes src/data/ability-balance.js for the Developer
// screen. Run: node tools/ability-balance.mjs [snaps]
import { writeFileSync } from 'node:fs';
import { simulatePlay } from '../src/sim/engine.js';
import { PLAYS, OFFENSE_IDS, DEFENSE_IDS } from '../src/data/playbook.js';
import { SPECIES_DEX, TRAITS } from '../src/data/species.js';
import { createRng } from '../src/core/rng.js';
import { generateMonster, effectiveAttributes } from '../src/data/monsters.js';
import { positionOf, OFFENSE_SLOTS, DEFENSE_SLOTS } from '../src/data/personnel.js';

const N = Number(process.argv[2]) || 2000;
const OFF_POS = new Set(['QB', 'RB', 'WR', 'TE', 'OL', 'K']);
const TURNOVER_YARDS = 45; // a turnover is worth about 45 yards of field position
const subjects = [...SPECIES_DEX.filter((s) => s.ability), ...Object.keys(TRAITS).map((t) => SPECIES_DEX.find((s) => s.trait === t && s.position !== 'K')).filter(Boolean)];

function lineups(seed, subjectSide, slot, sp, withAbility) {
  const rng = createRng(seed); const off = {}, def = {};
  for (const s of OFFENSE_SLOTS) { const m = generateMonster(rng, { position: positionOf(s), quality: 68 }); off[s] = { attrs: effectiveAttributes(m), name: s, id: `o${s}` }; }
  for (const s of DEFENSE_SLOTS) { const m = generateMonster(rng, { position: positionOf(s), quality: 68 }); def[s] = { attrs: effectiveAttributes(m), name: s, id: `d${s}` }; }
  const t = subjectSide === 'off' ? off : def; if (t[slot] && withAbility) t[slot] = { ...t[slot], species: sp.id, name: sp.name };
  return { off, def };
}
function measure(sp) {
  const side = OFF_POS.has(sp.position) ? 'off' : 'def';
  const slot = (side === 'off' ? OFFENSE_SLOTS : DEFENSE_SLOTS).find((s) => positionOf(s) === sp.position);
  const arm = (withAbility) => {
    const r = { yards: 0, to: 0, sacks: 0, td: 0, plays: 0, onField: 0, fired: 0 }; let used = {};
    for (let i = 0; i < N; i++) {
      if (i % 60 === 0) used = {}; // a new game
      const o = PLAYS[OFFENSE_IDS[(i * 7 + 3) % OFFENSE_IDS.length]], d = PLAYS[DEFENSE_IDS[(i * 11 + 5) % DEFENSE_IDS.length]];
      if (side === 'off' ? !o.onField.includes(slot) : !d.onField.includes(slot)) continue; // the package leaves him off the field
      const { off, def } = lineups(1000 + Math.floor(i / 60), side, slot, sp, withAbility);
      const g = i % 60; const memory = { drive: `${Math.floor(i / 60)}:${Math.floor(g / 6)}`, half: g < 30 ? 'h1' : 'h2', quarter: 1 + Math.floor(g / 15), used };
      const s = simulatePlay({ offensePlay: o, defensePlay: d, offense: off, defense: def, ballOn: 20 + (i * 13) % 60, seed: 7 + i, options: { memory, frameEvery: 10000 } });
      for (const k of s.memoryUsed || []) used[k] = true;
      r.plays++; r.yards += s.yards; r.to += s.turnover ? 1 : 0; r.sacks += s.result === 'sack' ? 1 : 0; r.td += s.touchdown && !s.stats.defensiveScore ? 1 : 0;
      if (s.events.some((e) => e.kind === 'ability' && e.by === slot && e.side === side)) r.fired++;
    }
    return r;
  };
  const a = arm(true), b = arm(false); const per = (x, k) => x[k] / Math.max(1, x.plays);
  const sign = side === 'off' ? 1 : -1; // what helps his team: more yards on offense, fewer allowed on defense
  const dY = per(a, 'yards') - per(b, 'yards'), dTO = per(a, 'to') - per(b, 'to'), dSack = per(a, 'sacks') - per(b, 'sacks'), dTD = per(a, 'td') - per(b, 'td');
  const value = sign * dY - sign * dTO * TURNOVER_YARDS; // yards of field position per snap he is on the field
  return { id: sp.id, name: sp.name, rarity: sp.rarity, position: sp.position, side, ability: sp.ability?.name || TRAITS[sp.trait]?.name, kind: sp.ability ? 'signature' : 'trait', plays: a.plays,
    firedPct: +(100 * a.fired / Math.max(1, a.plays)).toFixed(1), value: +value.toFixed(2), dYards: +(sign * dY).toFixed(2), dTurnovers: +(100 * -sign * dTO).toFixed(2), dSacks: +(100 * dSack).toFixed(2), dTD: +(100 * dTD).toFixed(2) };
}
// Optional third argument: species ids to re-measure (comma-separated); the other rows are kept from the last run.
const only = process.argv[3] ? new Set(process.argv[3].split(',')) : null;
const t0 = Date.now(); const rows = [];
const prev = only ? (await import('../src/data/ability-balance.js')).ABILITY_BALANCE.rows : [];
for (const sp of subjects) { if (only && !only.has(sp.id)) { const old = prev.find((r) => r.id === sp.id); if (old) rows.push(old); continue; } rows.push(measure(sp)); process.stdout.write('.'); }
rows.sort((x, y) => y.value - x.value);
const out = `// Generated by tools/ability-balance.mjs on ${new Date().toISOString().slice(0, 10)} (${N} paired snaps each). Do not edit by hand.\n// value: yards of field position per snap on the field (turnovers at ${TURNOVER_YARDS} yards); dTurnovers, dSacks, dTD per 100 snaps.\nexport const ABILITY_BALANCE = Object.freeze(${JSON.stringify({ snaps: N, generated: new Date().toISOString().slice(0, 10), rows }, null, 0)});\n`;
writeFileSync(new URL('../src/data/ability-balance.js', import.meta.url), out);
console.log(`\n${rows.length} measured in ${Math.round((Date.now() - t0) / 1000)} s`);
for (const r of rows) console.log(`${r.value.toFixed(2).padStart(6)}  ${r.kind === 'trait' ? 'trait    ' : r.rarity.padEnd(9)} ${r.ability.padEnd(16)} ${r.name.padEnd(10)} ${r.position.padEnd(3)} fired ${r.firedPct}%  yds ${r.dYards}  TO/100 ${r.dTurnovers}  sacks/100 ${r.dSacks}`);
