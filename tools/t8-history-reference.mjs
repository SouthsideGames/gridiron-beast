// Owner ruling N8b D1: precompute the post-history reference bands used by founding-roster selection (src/franchise/t8/selection.js)
// and write src/data/t8-history-reference.generated.js. A pure cache: every band is exactly what computeHistoryBand returns at run
// time (tests/task8-selection.test.js recomputes a sample and compares), and a band whose form data changed is ignored and
// recomputed in the game. Re-run after changing the Dex forms, the career simulation, ageing or the selection constants.
//   node tools/t8-history-reference.mjs            (all stage-0 non-legendary forms; about 5 minutes)
import fs from 'node:fs';
import { FORMS } from '../src/data/beast-dex.js';
import * as S from '../src/franchise/t8/selection.js';

const START_AGES = [21, 22]; // founding careers start at 21 or 22 (careerYears in src/data/monsters.js)
const PROFILES = ['starter', 'rotation', 'depth'];
const forms = FORMS.filter((f) => f.stage === 0 && f.rarity !== 'legendary');
const bands = {}; const t0 = Date.now();
forms.forEach((f, k) => {
  for (const a of START_AGES) for (const p of PROFILES) bands[S.bandKey(f.id, a, p)] = { f: S.formFingerprint(f.id), v: S.encodeBand(S.computeHistoryBand(f.id, a, p)) };
  if (k % 20 === 19) console.error(`${k + 1}/${forms.length} forms, ${((Date.now() - t0) / 1000).toFixed(0)}s`);
});
const table = { size: S.REFERENCE_SIZE, seasons: S.BAND_SEASONS, bands };
const out = new URL('../src/data/t8-history-reference.generated.js', import.meta.url);
fs.writeFileSync(out, `// GENERATED by tools/t8-history-reference.mjs — do not edit. Post-history reference bands (owner ruling N8b D1):\n// { size, seasons, bands: { "form|startAge|profile": { f: form fingerprint, v: per-season OVR counts } } }.\nexport const HISTORY_REFERENCE = ${JSON.stringify(table)};\n`);
console.error(`${Object.keys(bands).length} bands, ${((Date.now() - t0) / 1000).toFixed(0)}s, ${fs.statSync(out).size} bytes`);
