import test from 'node:test';
import assert from 'node:assert/strict';
const store = new Map();
globalThis.localStorage = { getItem: (k) => (store.has(k) ? store.get(k) : null), setItem: (k, v) => store.set(k, String(v)), removeItem: (k) => store.delete(k) };
const { createFranchise, hireDefaultStaff } = await import('../src/franchise/franchise.js');
const { registerCaptainScreens } = await import('../src/ui/screens/captains.js');
const f = createFranchise({ owner: { first: 'Cap', last: 'Tain' }, club: 'Ember City Beasts', seed: 41 }); hireDefaultStaff(f);
const screens = new Map(); let renders = 0;
const Router = { registerScreen: (n, s) => screens.set(n, s), render() { renders++; }, go() {} };
registerCaptainScreens(Router, { f, save() {} });
const screen = screens.get('captains');
const root = () => { const listeners = {}; return { listeners, addEventListener: (n, fn) => (listeners[n] ||= []).push(fn), querySelector: () => null, querySelectorAll: () => [], contains: () => true }; };
const intro = (html) => /class="panel tight cap-intro"/.test(html);
test('Team Captains shows its explanations on the first visit, folds them afterwards, and the info button brings them back', () => {
  const first = screen.render({ f });
  assert.ok(intro(first), 'first visit explains captains');
  assert.match(first, /data-action="cap-info" aria-expanded="true"/);
  const r1 = root(); screen.mount(r1); screen.unmount();
  const again = screen.render({ f });
  assert.ok(!intro(again), 'later visits start folded');
  assert.doesNotMatch(again, /cap-note/);
  assert.match(again, /data-action="cap-info" aria-expanded="false"/);
  const r2 = root(); screen.mount(r2);
  for (const fn of r2.listeners.click || []) fn({ target: { closest: (s) => (s.includes('data-action') ? { dataset: { action: 'cap-info' }, } : null) }, preventDefault() {} });
  assert.ok(renders > 0, 'the info button redraws the screen');
  assert.ok(intro(screen.render({ f })), 'info button brings the explanations back');
  screen.unmount();
  assert.ok(!intro(screen.render({ f })), 'and the next visit is folded again');
});
