const RULE_CACHE = new Map();
const BOUNDED_PHRASES = PHRASES.map(([pattern, replacement]) => [new RegExp(String.raw`(?<![\w])(?:${pattern.source})(?![\w])`, pattern.flags), replacement]);
export function plainAbilityRule(rule) {
  const original = String(rule || '');
  if (RULE_CACHE.has(original)) return RULE_CACHE.get(original);
  let text = original;
  const exact = {
    'Triggering attacker; if invalid, current opposing active monster': 'Hit back at the attacker. If that attacker is no longer a valid target, hit the enemy fighting now instead.',
    'Three hits, no separate cooldown approved.': 'Charge up by surviving three hits. There is no extra wait after the ability fires.',
    'Retain partial charge through rotations; reset each Clash.': 'Keep any unfinished charge when switching out. Start with no charge in each new Clash.',
    'No separate cooldown. No second bar or charging while ignited. Resume following carry. Two-point attempts neither charge nor trigger ignition. Existing fields still apply during conversions.': 'There is no extra wait between uses. While ignited, you cannot fill another charge bar. Start charging again on the next carry. Two-point tries cannot build charge or start ignition. Fields already on the ground still affect those tries.',
    'No receiving/return charge or activation. Stuns, fields, forced movement, out of bounds, strips and fumbles still apply.': 'Catches and kick returns cannot charge or start this ability. Stuns, fields, forced movement, going out of bounds, strips, and fumbles can still affect the runner.',
  };
  if (exact[text]) { RULE_CACHE.set(original, exact[text]); return exact[text]; }
  // Word boundaries keep changes out of names and other words.
  for (const [pattern, replacement] of BOUNDED_PHRASES) text = text.replace(pattern, replacement);
  text = text.replace(/Invalid attacker redirects to opposing active monster\./g, 'If the original attacker is no longer a valid target, hit the enemy fighting now instead.');
  text = text.replace(/(mastery|damage|heal|cooldown|for|at|old)(?=\d)/gi, '$1 ').replace(/(\d)(?=(?:plays|turns|yards|wide|long|charge)\b)/gi, '$1 ').replace(/<=/g, ' at most ').replace(/>=/g, ' at least ');
  text = text.replace(/;\s*/g, '. ').replace(/\.\s*\./g, '.');
  const result = text.split(/(?<=[.!?])\s+(?=[A-Za-z])/).map(line => line.charAt(0).toUpperCase() + line.slice(1)).join('\n');
  RULE_CACHE.set(original, result);
  return result;
}
